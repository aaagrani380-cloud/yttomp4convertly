create or replace function public.ensure_credit_account(target_user_id uuid)
returns public.credit_accounts
language plpgsql
security definer
set search_path = public
as $$
declare row public.credit_accounts;
begin
  insert into public.credit_accounts(user_id, balance, monthly_allowance)
  values(target_user_id, 600, 600)
  on conflict (user_id) do nothing;
  select * into row from public.credit_accounts where user_id=target_user_id;
  if row.period_end <= now() then
    update public.credit_accounts set balance=monthly_allowance, period_start=date_trunc('month', now()), period_end=date_trunc('month', now()) + interval '1 month' where user_id=target_user_id returning * into row;
    insert into public.credit_ledger(user_id, amount, kind, reference_id, reason)
    values(target_user_id, row.monthly_allowance, 'monthly_reset', 'monthly-reset-'||to_char(now(),'YYYY-MM'), 'Monthly Pro credit reset')
    on conflict (reference_id) do nothing;
  end if;
  return row;
end;
$$;

grant execute on function public.ensure_credit_account(uuid) to service_role;

