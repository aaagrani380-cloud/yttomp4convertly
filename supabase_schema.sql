create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  display_name text,
  role public.user_role not null default 'user',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  provider text not null default 'safepay',
  provider_customer_id text,
  provider_subscription_id text unique,
  plan text not null default 'pro_monthly',
  status public.subscription_status not null default 'trialing',
  current_period_start timestamptz,
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.conversions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete set null,
  source text not null default 'youtube',
  source_url text not null,
  quality integer not null check (quality between 144 and 2160),
  format text not null default 'mp4',
  status public.conversion_status not null default 'queued',
  progress integer not null default 0 check (progress between 0 and 100),
  job_id text,
  output_path text,
  download_expires_at timestamptz,
  error_message text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists conversions_user_created_idx on public.conversions(user_id, created_at desc);
create index if not exists conversions_status_created_idx on public.conversions(status, created_at);

create table if not exists public.referrals (
  id uuid primary key default gen_random_uuid(),
  referrer_id uuid not null references public.profiles(id) on delete cascade,
  referred_user_id uuid references public.profiles(id) on delete set null,
  referral_code text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  unique(referrer_id, referred_user_id)
);

