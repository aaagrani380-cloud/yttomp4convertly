create or replace function public.consume_credits(target_user_id uuid, credit_amount integer, reference_id text)
returns table(ok boolean, balance integer, code text, message text)
language plpgsql
security definer
set search_path = public
as $$
declare current_balance integer;
begin
  if credit_amount <= 0 then return query select true, 0, 'NOOP', 'No credits required.'; return; end if;
  perform public.ensure_credit_account(target_user_id);
  if exists(select 1 from public.credit_ledger where credit_ledger.reference_id=consume_credits.reference_id and kind='debit') then
    select balance into current_balance from public.credit_accounts where user_id=target_user_id;
    return query select true, current_balance, 'ALREADY_DEBITED', 'Credits already reserved.'; return;
  end if;
  update public.credit_accounts set balance=balance-credit_amount where user_id=target_user_id and balance >= credit_amount returning balance into current_balance;
  if current_balance is null then
    select balance into current_balance from public.credit_accounts where user_id=target_user_id;
    return query select false, coalesce(current_balance,0), 'INSUFFICIENT_CREDITS', 'Not enough credits.'; return;
  end if;
  insert into public.credit_ledger(user_id, amount, kind, reference_id, reason) values(target_user_id, -credit_amount, 'debit', reference_id, 'Conversion credit reservation');
  return query select true, current_balance, 'OK', 'Credits reserved.';
end;
$$;
grant execute on function public.consume_credits(uuid,integer,text) to service_role;

create or replace function public.refund_credits(target_user_id uuid, credit_amount integer, reference_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare new_balance integer;
begin
  if credit_amount <= 0 then return true; end if;
  if exists(select 1 from public.credit_ledger where credit_ledger.reference_id='refund-'||refund_credits.reference_id) then return true; end if;
  update public.credit_accounts set balance=balance+credit_amount where user_id=target_user_id returning balance into new_balance;
  if new_balance is null then return false; end if;
  insert into public.credit_ledger(user_id, amount, kind, reference_id, reason) values(target_user_id, credit_amount, 'refund', 'refund-'||reference_id, 'Conversion failed or cancelled');
  return true;
end;
$$;
grant execute on function public.refund_credits(uuid,integer,text) to service_role;

create or replace function public.grant_credits(target_user_id uuid, credit_amount integer, reason text default 'Admin credit grant')
returns text
language plpgsql
security definer
set search_path = public
as $$
begin
  if credit_amount <= 0 then raise exception 'Credit amount must be positive'; end if;
  perform public.ensure_credit_account(target_user_id);
  update public.credit_accounts set balance=balance+credit_amount where user_id=target_user_id;
  insert into public.credit_ledger(user_id, amount, kind, reference_id, reason) values(target_user_id, credit_amount, 'grant', 'grant-'||gen_random_uuid()::text, reason);
  return 'granted';
end;
$$;
grant execute on function public.grant_credits(uuid,integer,text) to service_role;
